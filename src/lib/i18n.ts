const dictionaries: Record<Lang, typeof en> = { en, th };

export type TranslationKey = keyof typeof en;

let current: Lang = loadLang();

function loadLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === "th" ? "th" : "en";
  } catch {
    return "en";
  }
}

const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* storage unavailable */
  }
  document.documentElement.lang = lang;
  listeners.forEach((fn) => fn());
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Re-render hook: returns the current language and updates on change. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLang);
}

export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  let text: string = dictionaries[current][key] ?? dictionaries.en[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}
